"""Rasterize Inter Medium clock glyphs into fixed-width A8 cells.

Usage: python tools/build_clock_font.py path/to/Inter.ttf
Source: google/fonts ofl/inter/Inter[opsz,wght].ttf (SIL OFL).
Requires Pillow on the build computer; firmware uses only the generated bytes.
"""
from pathlib import Path
import sys
from PIL import Image, ImageDraw, ImageFont

CHARS = "0123456789:-"
WIDTH, HEIGHT, SCALE = 28, 48, 4
font = ImageFont.truetype(sys.argv[1], 44 * SCALE)
font.set_variation_by_axes([32, 500])
result = bytearray()
for char in CHARS:
    cell = Image.new("L", (WIDTH * SCALE, HEIGHT * SCALE))
    draw = ImageDraw.Draw(cell)
    left, _, right, _ = draw.textbbox((0, 0), char, font=font, anchor="ls")
    x = (WIDTH * SCALE - (right - left)) / 2 - left
    draw.text((x, 40 * SCALE), char, font=font, fill=255, anchor="ls")
    result.extend(cell.resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS).tobytes())
Path("assets/clock-inter.a8").write_bytes(result)
print(f"Generated {len(result)} bytes: {CHARS}")
